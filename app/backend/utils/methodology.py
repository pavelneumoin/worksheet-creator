def block(subject,text):
    value=text.casefold()
    if subject=='physics':return 'physics'
    if any(x in value for x in ('\\sin','\\cos','\\tan','\\cot','тригонометр')):return 'trigonometry'
    if any(x in value for x in ('\\log','\\ln','логарифм')):return 'logarithms'
    if any(x in value for x in ('треуголь','окружност','параллел','геометр','докажите')):return 'geometry'
    if any(x in value for x in ('скорость','за час','сплав','вклад','кредит','производительност','движени','проехал')):return 'word'
    if subject in ('chemistry', 'other'):
        return 'general'
    return 'algebra'

def guide(subject,text):
    key=block(subject,text)
    return {'key':key,'title':GUIDES[key][0],'checks':GUIDES[key][1]}
